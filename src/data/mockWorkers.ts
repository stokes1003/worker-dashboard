const generateRandomDate = (start: Date, end: Date) => {
  return new Date(
    start.getTime() + Math.random() * (end.getTime() - start.getTime())
  );
};

const generateRandomExperience = () => {
  // Generate experience with a normal distribution around 6 years
  const years = Math.max(0, Math.round(Math.random() * 9)); // 0-9 years range
  const startDate = new Date();
  startDate.setFullYear(startDate.getFullYear() - years);
  const endDate = Math.random() > 0.3 ? new Date() : null;

  return {
    id: crypto.randomUUID(),
    company: `Company ${Math.floor(Math.random() * 1000)}`,
    position: `Position ${Math.floor(Math.random() * 100)}`,
    startDate: startDate.toISOString().split("T")[0],
    endDate: endDate ? endDate.toISOString().split("T")[0] : null,
    description: `Description ${Math.floor(Math.random() * 1000)}`,
    skills: skills.slice(0, Math.floor(Math.random() * 5) + 1),
  };
};

const generateRandomCertification = () => {
  return {
    id: crypto.randomUUID(),
    name: certifications[Math.floor(Math.random() * certifications.length)],
    issuingOrganization: `Organization ${Math.floor(Math.random() * 100)}`,
    dateObtained: generateRandomDate(new Date(2010, 0, 1), new Date())
      .toISOString()
      .split("T")[0],
  };
};

